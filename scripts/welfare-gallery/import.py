#!/usr/bin/env python3
"""「带上她的眼睛」作品集画廊 · 素材导入脚本

输入精选清单（scripts/welfare-gallery/<batch>.picks.json，由照片编辑环节产出），
只对清单内文件做 WebP 压缩（长边 ≤2560、q82），生成 src/data/welfare-gallery.ts，
并打印逐条 wrangler r2 object put 上传命令。

原则：R2 只存入选图。未入选素材不压缩、不上传、不产生任何对象存储副本。

用法：
  python3 scripts/welfare-gallery/import.py                 # 本地预览模式（/r2-preview 前缀）
  python3 scripts/welfare-gallery/import.py --r2            # R2 模式（绝对 URL，上传后用）
  python3 scripts/welfare-gallery/import.py --picks <path>  # 指定其他批次清单

依赖：python3 + Pillow（缺 Pillow 时先 `pip3 install Pillow`）
"""
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

from PIL import Image, ImageOps

REPO = Path(__file__).resolve().parents[2]
LONG_EDGE = 2560
QUALITY = 82
R2_BASE = "https://r2.xn--seeker-ng2jm403afb4a.club"
PREVIEW_BASE = "/r2-preview"

TS_HEAD = """// AUTO-GENERATED by scripts/welfare-gallery/import.py —— 请勿手改。
// 数据源：scripts/welfare-gallery/{batchId}.picks.json（照片编辑定稿清单）。
// author/age 为保留字段（暂不在页面展示）；src 为 R2 对象 key 对应的完整 URL。

export interface WelfareGalleryPhoto {
  /** 图片完整 URL */
  src: string;
  /** 原始像素尺寸（布局与 CLS 预留） */
  w: number;
  h: number;
  /** 学校全称 */
  school: string;
  /** 小摄影师姓名（保留字段，暂不展示） */
  author?: string;
  /** 年龄（保留字段，暂不展示） */
  age?: number;
  /** 所属主题 id */
  theme: string;
  /** 章内顺序（从 1 起），排序即编辑 */
  order: number;
  /** 一句平实的画面描述 */
  alt: string;
}

export interface WelfareGalleryTheme {
  id: string;
  title: string;
  /** 编辑导语 */
  note: string;
  photos: WelfareGalleryPhoto[];
}

export interface WelfareGalleryBatch {
  id: string;
  label: string;
  photoCount: number;
  schoolCount: number;
}

/** 落地页入口区块的单张预览瓷砖（各主题首图） */
export interface WelfareEntryTile {
  src: string;
  w: number;
  h: number;
  alt: string;
  title: string;
  no: string;
}

export const WELFARE_GALLERY_BATCH: WelfareGalleryBatch = {batch};
"""

TS_PHOTO = (
    "      {\n"
    "        src: {src},\n"
    "        w: {w},\n"
    "        h: {h},\n"
    "        school: {school},\n"
    "        author: {author},\n"
    "        age: {age},\n"
    "        theme: {theme},\n"
    "        order: {order},\n"
    "        alt: {alt},\n"
    "      },"
)


def ts_photo(**kw) -> str:
    out = TS_PHOTO
    for k, v in kw.items():
        out = out.replace("{" + k + "}", str(v))
    return out


def ts_theme(theme_id: str, title: str, note: str, photos: str) -> str:
    return (
        "  {\n"
        f"    id: {ts_str(theme_id)},\n"
        f"    title: {ts_str(title)},\n"
        f"    note: {ts_str(note)},\n"
        "    photos: [\n"
        f"{photos}\n"
        "    ],\n"
        "  },"
    )


def ts_str(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def load_picks(path: Path) -> dict:
    data = json.loads(path.read_text(encoding="utf-8"))
    batch = data["batch"]["id"]
    if not re.fullmatch(r"w\d{2}", batch):
        sys.exit(f"批次 id 非法：{batch}（应为 w01 这类格式）")
    for theme in data["themes"]:
        if not theme["picks"]:
            sys.exit(f"主题 {theme['id']} 没有照片")
    return data


def compress(src: Path, dst: Path) -> tuple[int, int]:
    im = Image.open(src)
    im = ImageOps.exif_transpose(im)
    if im.mode not in ("RGB", "L"):
        im = im.convert("RGB")
    if max(im.size) > LONG_EDGE:
        im.thumbnail((LONG_EDGE, LONG_EDGE), Image.LANCZOS)
    dst.parent.mkdir(parents=True, exist_ok=True)
    im.save(dst, "WEBP", quality=QUALITY, method=6)
    return im.size


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--picks", default=str(Path(__file__).parent / "w01.picks.json"))
    parser.add_argument("--r2", action="store_true", help="生成 R2 绝对 URL（上传后使用）")
    args = parser.parse_args()

    picks_path = Path(args.picks)
    data = load_picks(picks_path)
    batch = data["batch"]["id"]
    base = R2_BASE if args.r2 else PREVIEW_BASE

    out_dir = REPO / "public" / "r2-preview" / "welfare" / "bring-her-eyes" / "gallery" / batch
    themes_ts = []
    n_total = 0
    schools: set[str] = set()
    wrangler_cmds: list[str] = []

    for theme in data["themes"]:
        photos_ts = []
        for pick in theme["picks"]:
            n_total += 1
            src = Path(pick["path"])
            if not src.is_file():
                sys.exit(f"找不到素材文件：{src}")
            key = f"welfare/bring-her-eyes/gallery/{batch}/{n_total:03d}.webp"
            dst = REPO / "public" / "r2-preview" / key
            w, h = compress(src, dst)
            size_kb = dst.stat().st_size // 1024
            print(f"  [{n_total:03d}] {theme['id']} #{pick['order']} <- {src.name} {w}x{h} {size_kb}KB")
            schools.add(pick["school"])
            photos_ts.append(
                ts_photo(
                    src=ts_str(f"{base}/{key}"),
                    w=w, h=h,
                    school=ts_str(pick["school"]),
                    author=ts_str(pick["author"]) if pick.get("author") else "undefined",
                    age=str(pick["age"]) if pick.get("age") else "undefined",
                    theme=ts_str(theme["id"]),
                    order=pick["order"],
                    alt=ts_str(pick["alt"]),
                )
            )
            content_type = "image/webp"
            wrangler_cmds.append(
                f"wrangler r2 object put seeker-homepage-assets/{key} "
                f"--file {dst} --remote --content-type {content_type} "
                '--cache-control "public, max-age=31536000, immutable"'
            )
        themes_ts.append(
            ts_theme(theme["id"], theme["title"], theme["note"], "\n".join(photos_ts))
        )

    batch_ts = (
        '{\n'
        f'  id: {ts_str(batch)},\n  label: {ts_str(data["batch"]["label"])},\n'
        f"  photoCount: {n_total},\n  schoolCount: {len(schools)},\n"
        '}'
    )
    ts = TS_HEAD.replace("{batchId}", batch).replace("{batch}", batch_ts) + "\n\nexport const WELFARE_GALLERY_THEMES: WelfareGalleryTheme[] = [\n" + "\n".join(themes_ts) + "\n];\n"

    out_ts = REPO / "src" / "data" / "welfare-gallery.ts"
    out_ts.write_text(ts, encoding="utf-8")
    print(f"\n✓ {n_total} 张已压缩 → {out_dir}")
    print(f"✓ 数据文件已生成 → {out_ts}（base = {base}）")
    print(f"✓ 共 {len(schools)} 所学校\n")

    print("# R2 上传命令（确认后逐条执行，只上传以下入选图）：")
    for cmd in wrangler_cmds:
        print(cmd)


if __name__ == "__main__":
    main()
